/**
 * Katalog bagian kendaraan yang dipakai sebagai fokus pemeriksaan Mekanik
 * maupun nilai bagian bermasalah pada {@link MasalahKendaraan}.
 */
public enum FokusBagian {
    /** Sistem mesin utama kendaraan. */
    MESIN,
    /** Sistem pemindah tenaga dan rasio gigi. */
    TRANSMISI,
    /** Komponen pengereman kendaraan. */
    REM,
    /** Sistem suspensi dan kemudi kendaraan. */
    SUSPENSI_KEMUDI,
    /** Sistem kelistrikan dan komponennya. */
    KELISTRIKAN,
    /** Sistem pendinginan mesin. */
    SISTEM_PENDINGIN,
    /** Sistem pembuangan gas kendaraan. */
    SISTEM_PEMBUANGAN,
    /** Rangka dan sasis kendaraan. */
    RANGKA_CHASIS,
    /** Panel dan komponen eksterior kendaraan. */
    BODY_EKSTERIOR,
    /** Kabin, interior, dan pendingin udara. */
    INTERIOR_AC,
    /** Roda dan ban kendaraan. */
    RODA_BAN
}
