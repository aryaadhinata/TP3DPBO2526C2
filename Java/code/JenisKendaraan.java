/**
 * Kategori kendaraan yang dipakai untuk menyimpan tipe kendaraan dan
 * membatasi penanganan pegawai berdasarkan spesialisasinya.
 */
public enum JenisKendaraan {
    /** Kendaraan roda empat atau lebih yang dikategorikan sebagai mobil. */
    MOBIL,
    /** Kendaraan roda dua yang dikategorikan sebagai motor. */
    MOTOR
}
